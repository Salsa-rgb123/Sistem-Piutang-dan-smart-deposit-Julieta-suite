do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'customers', 'invoices', 'deposits', 'deposit_damages',
    'transaction_logs', 'app_settings', 'service_catalog', 'location_zones'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('drop policy if exists authenticated_access on public.%I', table_name);
    execute format(
      'create policy authenticated_access on public.%I for select to authenticated using (true)',
      table_name
    );
    execute format('grant select on public.%I to authenticated', table_name);
    execute format('revoke insert, update, delete on public.%I from anon, authenticated', table_name);
  end loop;
end;
$$;

create or replace function public.create_customer(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  saved_customer public.customers;
  actor text := coalesce(nullif(left(trim(p_payload->>'admin_name'), 80), ''), 'Admin Julieta');
begin
  if length(regexp_replace(coalesce(p_payload->>'phone', ''), '[^0-9]', '', 'g')) < 8 then
    raise exception 'Nomor WhatsApp minimal 8 digit';
  end if;
  if nullif(trim(p_payload->>'bank_name'), '') is null
     or nullif(trim(p_payload->>'account_number'), '') is null then
    raise exception 'Nama bank dan nomor rekening wajib diisi';
  end if;

  insert into public.customers (name, phone, email, event_date, venue, created_at, admin_name, bank_name, account_number)
  values (
    trim(p_payload->>'name'), trim(p_payload->>'phone'), coalesce(p_payload->>'email', ''),
    nullif(p_payload->>'event_date', '')::date, coalesce(p_payload->>'venue', ''),
    coalesce(nullif(p_payload->>'recorded_at', '')::date + localtime, now()),
    actor, trim(p_payload->>'bank_name'), trim(p_payload->>'account_number')
  ) returning * into saved_customer;

  insert into public.transaction_logs (transaction_type, reference_id, admin_name, details, created_at)
  values ('Pelanggan', saved_customer.id, actor, 'Tambah pelanggan ' || saved_customer.name, saved_customer.created_at);
  return to_jsonb(saved_customer);
end;
$$;

create or replace function public.update_customer(p_customer_id bigint, p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  saved_customer public.customers;
begin
  if length(regexp_replace(coalesce(p_payload->>'phone', ''), '[^0-9]', '', 'g')) < 8 then
    raise exception 'Nomor WhatsApp minimal 8 digit';
  end if;
  if nullif(trim(p_payload->>'bank_name'), '') is null
     or nullif(trim(p_payload->>'account_number'), '') is null then
    raise exception 'Nama bank dan nomor rekening wajib diisi';
  end if;

  update public.customers set
    name = trim(p_payload->>'name'), phone = trim(p_payload->>'phone'),
    email = coalesce(p_payload->>'email', ''), event_date = nullif(p_payload->>'event_date', '')::date,
    venue = coalesce(p_payload->>'venue', ''), bank_name = trim(p_payload->>'bank_name'),
    account_number = trim(p_payload->>'account_number')
  where id = p_customer_id returning * into saved_customer;
  if not found then raise exception 'Pelanggan tidak ditemukan'; end if;
  return to_jsonb(saved_customer);
end;
$$;

create or replace function public.create_invoice(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  selected_count integer;
  found_count integer;
  service_total bigint;
  zone_fee bigint;
  paid bigint := coalesce(nullif(p_payload->>'paid_amount', '')::bigint, 0);
  services jsonb;
  service_names text;
  invoice_row public.invoices;
  actor text := coalesce(nullif(left(trim(p_payload->>'admin_name'), 80), ''), 'Admin Julieta');
  recorded_at timestamptz := coalesce(nullif(p_payload->>'recorded_at', '')::date + localtime, now());
begin
  select count(*) into selected_count
  from (select distinct value from jsonb_array_elements_text(coalesce(p_payload->'service_types', '[]'::jsonb))) selected;
  select count(*), coalesce(sum(c.standard_price), 0),
         coalesce(jsonb_agg(jsonb_build_object('name', c.name, 'amount', c.standard_price) order by c.name), '[]'::jsonb),
         string_agg(c.name, ', ' order by c.name)
  into found_count, service_total, services, service_names
  from (select distinct value from jsonb_array_elements_text(coalesce(p_payload->'service_types', '[]'::jsonb))) selected
  join public.service_catalog c on c.name = selected.value;

  if selected_count = 0 or selected_count <> found_count then
    raise exception 'Pilih minimal satu jasa yang terdaftar';
  end if;
  select fee into zone_fee from public.location_zones where name = p_payload->>'location_zone';
  if not found then raise exception 'Pilih zona lokasi acara'; end if;
  if paid < 0 or paid > service_total + zone_fee then
    raise exception 'Nominal pembayaran awal tidak valid';
  end if;

  insert into public.invoices (
    invoice_number, customer_id, description, total_amount, paid_amount, due_date, status,
    created_at, admin_name, service_type, service_amount, location_zone, location_fee, services_json
  ) values (
    'INV-' || to_char(clock_timestamp(), 'YYMMDDHH24MISSMS'),
    (p_payload->>'customer_id')::bigint,
    coalesce(nullif(trim(p_payload->>'description'), ''), service_names),
    service_total + zone_fee, paid, (p_payload->>'due_date')::date,
    case when paid >= service_total + zone_fee then 'Lunas' when paid > 0 then 'Sebagian' else 'Menunggu' end,
    recorded_at, actor, service_names, service_total, p_payload->>'location_zone', zone_fee, services
  ) returning * into invoice_row;

  insert into public.transaction_logs (transaction_type, reference_id, admin_name, details, created_at)
  values ('Piutang', invoice_row.id, actor, 'Catat ' || invoice_row.invoice_number, recorded_at);
  return to_jsonb(invoice_row);
end;
$$;

create or replace function public.create_deposit(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  deposit_row public.deposits;
  amount_value bigint := (p_payload->>'amount')::bigint;
  actor text := coalesce(nullif(left(trim(p_payload->>'admin_name'), 80), ''), 'Admin Julieta');
  recorded_at timestamptz := coalesce(nullif(p_payload->>'recorded_at', '')::date + localtime, now());
begin
  if amount_value <= 0 then raise exception 'Nominal deposit harus lebih dari nol'; end if;
  insert into public.deposits (customer_id, amount, notes, deposited_at, admin_name)
  values ((p_payload->>'customer_id')::bigint, amount_value, coalesce(p_payload->>'notes', ''), recorded_at, actor)
  returning * into deposit_row;
  insert into public.transaction_logs (transaction_type, reference_id, admin_name, details, created_at)
  values ('Deposit', deposit_row.id, actor, 'Setor deposit sebesar Rp' || amount_value, recorded_at);
  return to_jsonb(deposit_row);
end;
$$;

create or replace function public.record_payment(p_invoice_id bigint, p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  invoice_row public.invoices;
  amount_value bigint := (p_payload->>'paid_amount')::bigint;
  actor text := coalesce(nullif(left(trim(p_payload->>'admin_name'), 80), ''), 'Admin Julieta');
  recorded_at timestamptz := coalesce(nullif(p_payload->>'recorded_at', '')::date + localtime, now());
begin
  select * into invoice_row from public.invoices where id = p_invoice_id for update;
  if not found or amount_value <= 0 or invoice_row.paid_amount + amount_value > invoice_row.total_amount then
    raise exception 'Pembayaran tidak valid atau melebihi sisa tagihan';
  end if;
  update public.invoices set paid_amount = paid_amount + amount_value,
    status = case when paid_amount + amount_value >= total_amount then 'Lunas' else 'Sebagian' end,
    admin_name = actor
  where id = p_invoice_id returning * into invoice_row;
  insert into public.transaction_logs (transaction_type, reference_id, admin_name, details, created_at)
  values ('Penagihan', p_invoice_id, actor, 'Pembayaran ' || invoice_row.invoice_number || ' sebesar Rp' || amount_value, recorded_at);
  return to_jsonb(invoice_row);
end;
$$;

create or replace function public.record_damage(p_deposit_id bigint, p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  deposit_row public.deposits;
  quantity_value integer := (p_payload->>'quantity')::integer;
  unit_cost bigint := (p_payload->>'replacement_cost')::bigint;
  total_value bigint;
  actor text := coalesce(nullif(left(trim(p_payload->>'admin_name'), 80), ''), 'Admin Julieta');
  recorded_at timestamptz := coalesce(nullif(p_payload->>'recorded_at', '')::date + localtime, now());
begin
  select * into deposit_row from public.deposits where id = p_deposit_id for update;
  total_value := quantity_value::bigint * unit_cost;
  if not found or quantity_value <= 0 or unit_cost <= 0
     or deposit_row.returned_amount + deposit_row.damaged_amount + total_value > deposit_row.amount then
    raise exception 'Potongan kerusakan melebihi sisa deposit';
  end if;
  insert into public.deposit_damages (deposit_id, item_name, quantity, replacement_cost, total_cost, admin_name, created_at)
  values (p_deposit_id, trim(p_payload->>'item_name'), quantity_value, unit_cost, total_value, actor, recorded_at);
  update public.deposits set damaged_amount = damaged_amount + total_value,
    status = 'Dipotong Kerusakan', admin_name = actor
  where id = p_deposit_id returning * into deposit_row;
  insert into public.transaction_logs (transaction_type, reference_id, admin_name, details, created_at)
  values ('Potongan kerusakan', p_deposit_id, actor, trim(p_payload->>'item_name') || ' x' || quantity_value || ', potongan Rp' || total_value, recorded_at);
  return to_jsonb(deposit_row);
end;
$$;

create or replace function public.return_deposit(p_deposit_id bigint, p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  deposit_row public.deposits;
  amount_value bigint := (p_payload->>'returned_amount')::bigint;
  remaining bigint;
  actor text := coalesce(nullif(left(trim(p_payload->>'admin_name'), 80), ''), 'Admin Julieta');
  recorded_at timestamptz := coalesce(nullif(p_payload->>'recorded_at', '')::date + localtime, now());
begin
  select * into deposit_row from public.deposits where id = p_deposit_id for update;
  if not found or amount_value <= 0
     or deposit_row.returned_amount + deposit_row.damaged_amount + amount_value > deposit_row.amount then
    raise exception 'Nominal pengembalian melebihi sisa deposit';
  end if;
  remaining := deposit_row.amount - deposit_row.returned_amount - deposit_row.damaged_amount - amount_value;
  update public.deposits set returned_amount = returned_amount + amount_value,
    status = case
      when remaining = 0 and damaged_amount = 0 then 'Dikembalikan'
      when damaged_amount > 0 then 'Dipotong Kerusakan'
      else 'Dikembalikan Sebagian'
    end,
    admin_name = actor
  where id = p_deposit_id returning * into deposit_row;
  insert into public.transaction_logs (transaction_type, reference_id, admin_name, details, created_at)
  values ('Pengembalian deposit', p_deposit_id, actor, 'Pengembalian sebesar Rp' || amount_value, recorded_at);
  return to_jsonb(deposit_row);
end;
$$;

