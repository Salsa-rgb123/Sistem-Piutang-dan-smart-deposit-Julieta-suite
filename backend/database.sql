create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  email text not null default '',
  event_date date,
  venue text not null default '',
  created_at timestamptz not null default now(),
  admin_name text not null default 'Admin Julieta',
  bank_name text not null default '',
  account_number text not null default ''
);

create table if not exists public.invoices (
  id bigint generated by default as identity primary key,
  invoice_number text not null unique,
  customer_id bigint not null references public.customers(id),
  description text not null,
  total_amount bigint not null check (total_amount > 0),
  paid_amount bigint not null default 0 check (paid_amount >= 0),
  due_date date not null,
  status text not null default 'Menunggu',
  created_at timestamptz not null default now(),
  admin_name text not null default 'Admin Julieta',
  service_type text not null default '',
  service_amount bigint not null default 0,
  location_zone text not null default '',
  location_fee bigint not null default 0,
  services_json jsonb not null default '[]'::jsonb
);

create table if not exists public.deposits (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers(id),
  amount bigint not null check (amount > 0),
  returned_amount bigint not null default 0 check (returned_amount >= 0),
  damaged_amount bigint not null default 0 check (damaged_amount >= 0),
  status text not null default 'Tersimpan',
  notes text not null default '',
  deposited_at timestamptz not null default now(),
  admin_name text not null default 'Admin Julieta'
);

create table if not exists public.deposit_damages (
  id bigint generated by default as identity primary key,
  deposit_id bigint not null references public.deposits(id) on delete cascade,
  item_name text not null,
  quantity integer not null check (quantity > 0),
  replacement_cost bigint not null check (replacement_cost > 0),
  total_cost bigint not null check (total_cost > 0),
  admin_name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.transaction_logs (
  id bigint generated by default as identity primary key,
  transaction_type text not null,
  reference_id bigint not null,
  admin_name text not null,
  details text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.app_settings (
  setting_key text primary key,
  setting_value text not null
);

create table if not exists public.service_catalog (
  name text primary key,
  min_price bigint not null,
  max_price bigint not null,
  standard_price bigint not null
);

create table if not exists public.location_zones (
  name text primary key,
  fee bigint not null
);

